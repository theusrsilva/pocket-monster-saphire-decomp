-- Glifo = { w = largura, px = { [linha] = { [coluna] = true } } } na célula da fonte.
local function build(rows, top)
  local g = { w = #rows[1], px = {} }
  for y, r in ipairs(rows) do
    for x = 1, #r do
      if r:sub(x, x) == "#" then
        g.px[top + y - 1] = g.px[top + y - 1] or {}
        g.px[top + y - 1][x - 1] = true
      end
    end
  end
  return g
end

local function addMark(g, mark, top)
  local m = MARKS[mark]
  local mw = #m[1]
  local ox = math.floor((g.w - mw) / 2 + 0.5)
  if g.w - mw == 1 then ox = 1 end
  for y, r in ipairs(m) do
    for x = 1, #r do
      if r:sub(x, x) == "#" then
        local cx = ox + x - 1
        if cx >= 0 then
          g.px[top + y - 1] = g.px[top + y - 1] or {}
          g.px[top + y - 1][cx] = true
        end
      end
    end
  end
  g.w = math.max(g.w, ox + mw)
  return g
end

local cache = { normal = {}, small = {} }

-- Glifo do caractere ch (UTF-8) na fonte "normal" ou "small"; nil se não houver.
function PixelFont.glyph(font, ch)
  local c = cache[font]
  if c[ch] ~= nil then return c[ch] or nil end
  local g
  if font == "normal" then
    local d = DECOMP[ch]
    if N[ch] then
      g = build(N[ch], 2)
    elseif d then
      -- maiúscula: acento nas linhas 0-1 (acima do corpo); minúscula: linhas 2-3 (altura das hastes)
      local lower = d[1]:match("^[a-z]$") or d[1] == "ı"
      g = build(N[d[1]], 2)
      addMark(g, d[2], lower and 2 or 0)
    end
  else
    local up = UPPER[ch] or ch:upper()
    local d = DECOMP[up]
    if up == "Ç" then
      g = build(S.C, 2)
      g.px[7] = { [1] = true }
    elseif S[up] then
      g = build(S[up], 2)
    elseif d then
      g = build(S[d[1]], 2)
      addMark(g, d[2], 0)
    end
  end
  c[ch] = g or false
  return g
end

-- Quebra a string UTF-8 em caracteres.
function PixelFont.chars(s)
  local t = {}
  for ch in s:gmatch("[%z\1-\127\194-\244][\128-\191]*") do t[#t + 1] = ch end
  return t
end

-- Largura em pixels com `gap` colunas entre letras.
function PixelFont.width(font, s, gap)
  local w, n = 0, 0
  for _, ch in ipairs(PixelFont.chars(s)) do
    local g = PixelFont.glyph(font, ch)
    if g then w = w + g.w; n = n + 1 end
  end
  return w + math.max(0, n - 1) * gap
end

-- Desenha s em plot(x, y) a partir de (x0, y0) = canto da célula. Devolve a largura usada.
function PixelFont.draw(font, s, x0, y0, gap, plot)
  local x = x0
  for _, ch in ipairs(PixelFont.chars(s)) do
    local g = PixelFont.glyph(font, ch)
    if g then
      for y, row in pairs(g.px) do
        for cx in pairs(row) do plot(x + cx, y0 + y) end
      end
      x = x + g.w + gap
    end
  end
  return x - x0 - gap
end

